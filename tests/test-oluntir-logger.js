'use strict';
const assert = require('assert');
const logger = require('../editor/js/core/oluntir-logger.js');
logger.clear();
logger.authorizeDirectory({ name: 'logs' }, 'logs', 'trace');
logger.clear();
logger.configure({ level: 'trace', maxEntries: 3, enabled: true });
logger.info('session', 'one', { n: 1 });
logger.warn('action', 'two');
logger.error('error', 'three', new Error('boom'));
logger.debug('resolver', 'four');
const state = logger.getState();
assert.strictEqual(state.buffered, 3);
assert.strictEqual(state.dropped, 1);
assert.strictEqual(logger.entries({ category: 'action' }).length, 1);
assert.strictEqual(logger.entries({ category: 'error' }).length, 1);
assert.ok(logger.FILES['shared-content']);
logger.revoke({ clearBuffer: true });
console.log('OLUNTIR-LOGGER-TEST ERFOLGREICH');
