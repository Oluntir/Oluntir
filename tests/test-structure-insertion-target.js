must(service.includes('OluntirStructureInsertionTarget'), 'Reusable insertion target service missing');
must(documentApi.includes('OluntirStructureResolver'), 'Semantic structure resolver contract missing');
must(documentApi.includes("templateRole === 'row'"), 'Bootstrap ROW role is not used as primary insertion structure');
must(documentApi.includes("parentRoles = new Set(['main', 'section', 'container', 'container-fluid'])"), 'Template layout parent roles missing');
must(documentApi.includes("'between-rows'"), 'Between-ROW insertion slot missing');
must(documentApi.includes("slotKind: 'before-row'"), 'Before-first-ROW insertion slot missing');
must(documentApi.includes("'after-last-row'"), 'After-last-ROW insertion slot missing');
must(documentApi.includes('parentIdentity'), 'Identity-based parent target missing');
must(documentApi.includes('anchorIdentity'), 'Identity-based anchor target missing');
must(!documentApi.includes('const undoStack'), 'Parallel document undo stack must not exist');
must(!documentApi.includes('const redoStack'), 'Parallel document redo stack must not exist');
must(adapter.includes('resolveInsertionTarget(target)'), 'Adapter target resolution missing');
must(adapter.includes('highlightInsertionTarget(target)'), 'Exact insertion-line highlighting missing');
must(service.includes('HIER PLATZIEREN') || css.includes('oluntir-row-insert-line'), 'Visible placement line missing');
must(service.includes('Bootstrap-Layoutbereiche mit ihren direkten ROWs'), 'ROW-slot guidance missing');
must(css.includes('.oluntir-row-slot-group'), 'ROW-slot group styling missing');
must(css.includes('.oluntir-row-insert-line'), 'Insertion-line styling missing');
must(gallery.includes("cfg.source !== 'framework-block'"), 'Framework gallery is not restricted to the drop workflow');
must(!gallery.includes('Am Seitenende einfügen'), 'Legacy fixed page-end option still present');
must(index.indexOf('structure-insertion-target.js') < index.indexOf('gallery.js'), 'Insertion target service must load before gallery');
