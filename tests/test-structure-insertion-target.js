const fs = require('fs');
const service = fs.readFileSync('editor/js/core/structure-insertion-target.js', 'utf8');
const documentApi = fs.readFileSync('editor/js/core/oluntir-document-api.js', 'utf8');
const adapter = fs.readFileSync('editor/integrations/grapesjs/grapesjs-adapter.js', 'utf8');
const gallery = fs.readFileSync('editor/js/features/gallery.js', 'utf8');
const css = fs.readFileSync('editor/css/editor.css', 'utf8');
