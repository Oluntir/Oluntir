'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const source = fs.readFileSync(path.join(__dirname, '../editor/js/core/startup.js'), 'utf8');
assert.ok(source.includes("const APP_VERSION = '2.2.0 BETA';"), 'Startup muss die aktuelle 2.2.0-BETA-Version anzeigen.');
const merge = source.indexOf("schemaVersion: STARTUP_SCHEMA,\n      appVersion: APP_VERSION,\n      lastOpenedAt");
assert.ok(merge >= 0, 'setMeta muss appVersion nach alten Projektmetadaten verbindlich auf die laufende Version setzen.');
assert.ok(source.includes("previousVersion !== APP_VERSION"), 'Beim Öffnen eines älteren Projekts muss die Vorversion nur als Migrationshistorie erhalten bleiben.');
assert.ok(source.includes('bestehendes Projekt wird kompatibel übernommen'), 'Der Startdialog muss 2.2.0 BETA als aktuelle Version zeigen und darf die alte Metadatenversion nicht als Tool-Version ausgeben.');
assert.ok(source.includes("action: 'existing', appVersion: APP_VERSION"), 'Die Session muss den aktuellen Versionsstand tragen.');
console.log('STARTUP-VERSION-MIGRATION-TEST ERFOLGREICH');
